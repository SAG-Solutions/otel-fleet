// OptionalInt is a tri-state PATCH field: Set=false means unchanged,
// Set=true with a nil Value clears the column, Set=true with a non-nil Value
// writes it. It carries the JSON distinction between an absent key and an
// explicit null into the store.
type OptionalInt struct {
	Set   bool
	Value *int
}

